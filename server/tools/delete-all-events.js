// Delete every TimetableEvent, and prove the attendance survived it.
//
// WHY THIS IS A TOOL AND NOT A DELETE STATEMENT
//
// "Clear the calendar" and "clear the calendar and the attendance that was taken
// against it" are one keystroke apart in SQL and unrecoverable apart in consequence. A
// register that has been marked is a record of who was in a room on a morning; the event
// is only the college's plan to be in it. The schema already encodes that difference --
// HndSession.timetableEventId is onDelete: SetNull, so a marked register survives its
// event and is merely unlinked -- and smoke-timetable-registers.mjs asserts it. This
// tool exists so the same guarantee is CHECKED at the moment of a bulk delete rather
// than assumed from a migration written months earlier.
//
// So it counts the marks before and after and refuses to report success if the number
// moved. A delete that silently took attendance with it would otherwise look exactly
// like a delete that did not.
//
//   node tools/delete-all-events.js                 # dry run, writes nothing
//   node tools/delete-all-events.js --apply         # delete
//
// ALWAYS pass DATABASE_URL explicitly. server/.env points at a live database, and the
// whole point of this file is that it is pointed somewhere deliberately.
const { PrismaClient } = require("@prisma/client");

const prisma = new PrismaClient();
const APPLY = process.argv.includes("--apply");

(async () => {
  const url = process.env.DATABASE_URL || "";
  if (!url) { console.error("FAILED: DATABASE_URL is not set. Pass it explicitly."); process.exit(1); }
  // The host is echoed before anything else happens, because the single most expensive
  // mistake available here is running this against the database you did not mean.
  const host = url.replace(/^.*@/, "").split("/")[0] || "(unknown)";
  console.log(`Database: ${host}`);
  console.log(APPLY ? "MODE: APPLY -- rows will be deleted.\n" : "MODE: dry run. Nothing will be written. Add --apply.\n");

  try {
    const events = await prisma.timetableEvent.count();
    // Taken BEFORE the delete so the comparison afterwards means something. Counting
    // only after would prove nothing: any number would look like the right one.
    const marksBefore = await prisma.attendanceMark.count();
    const linkedBefore = await prisma.hndSession.count({ where: { timetableEventId: { not: null } } });

    console.log(`  events                       ${events}`);
    console.log(`  registers linked to an event ${linkedBefore}`);
    console.log(`  attendance marks             ${marksBefore}`);

    if (!events) { console.log("\nNothing to delete."); return; }
    if (!APPLY) {
      console.log(`\nWould delete ${events} event(s).`);
      console.log(`Would leave ${marksBefore} attendance mark(s) untouched, and unlink ${linkedBefore} register(s).`);
      return;
    }

    // UNMARKED EVENT REGISTERS GO FIRST, AND THIS IS NOT AN OPTIMISATION.
    //
    // The two partial unique indexes on HndSession describe two different namespaces,
    // and SetNull moves a row between them:
    //
    //   linked:   ("timetableEventId", COALESCE("cohortId",'')) WHERE id IS NOT NULL
    //   unlinked: ("unitId","date","startTime")                 WHERE id IS NULL
    //
    // A merged class keeps one register PER GROUP -- the whole point of it -- so its
    // registers are distinguished only by cohortId. The unlinked index does not contain
    // cohortId, so the moment the event is deleted they all collapse onto one key and
    // collide with each other. Deleting any merged class with two or more groups
    // therefore fails outright, on this tool and through the API alike.
    //
    // Removing the unmarked ones first sidesteps that WITHOUT touching the guarantee
    // that matters: a register with no marks is one nobody ever took, it carries no
    // record of anybody, and it is regenerated by publishing the dates again. A register
    // WITH marks is left strictly alone here and still goes through SetNull, so the
    // tested behaviour -- a marked register survives its event -- is unchanged.
    const orphans = await prisma.hndSession.findMany({
      where: { timetableEventId: { not: null }, marks: { none: {} } },
      select: { id: true },
    });
    if (orphans.length) {
      const gone = await prisma.hndSession.deleteMany({ where: { id: { in: orphans.map((o) => o.id) } } });
      console.log(`\n  removed ${gone.count} unmarked register(s) belonging to those events`);
    }

    const del = await prisma.timetableEvent.deleteMany({});
    const marksAfter = await prisma.attendanceMark.count();
    const linkedAfter = await prisma.hndSession.count({ where: { timetableEventId: { not: null } } });
    const sessionsAfter = await prisma.hndSession.count();

    console.log(`\n  deleted ${del.count} event(s)`);
    console.log(`  registers still present      ${sessionsAfter}`);
    console.log(`  registers still linked       ${linkedAfter}  (expected 0 -- the FK is SetNull)`);
    console.log(`  attendance marks             ${marksAfter}`);

    // The assertion, not a log line. A non-zero exit is what makes this a check rather
    // than a note somebody skims past in a terminal.
    if (marksAfter !== marksBefore) {
      console.error(`\nFAILED: attendance changed -- ${marksBefore} marks before, ${marksAfter} after. Investigate before doing this anywhere else.`);
      process.exit(1);
    }
    console.log("\nOK: every attendance mark survived. The calendar is empty.");
  } finally {
    await prisma.$disconnect();
  }
})().catch((e) => { console.error("FAILED:", e.message); process.exit(1); });
